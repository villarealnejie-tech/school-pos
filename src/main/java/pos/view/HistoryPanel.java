    public HistoryPanel() {
        initComponents();
        salesModel = (DefaultTableModel) salesTable.getModel();
        itemsModel = (DefaultTableModel) itemsTable.getModel();

        salesTable.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        salesTable.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && controller != null) controller.selectSale(salesTable.getSelectedRow());
        });
    }

    public void setController(HistoryController controller) {
        this.controller = controller;
    }

    public void showSales(List<Sale> sales) {
        salesModel.setRowCount(0);
        for (Sale s : sales) {
            salesModel.addRow(new Object[]{s.id(), s.date(), s.cashier(),
                    Money.format(s.total()), Money.format(s.cash()), Money.format(s.change())});
        }
    }

    public void showItems(List<SaleItem> items) {
        itemsModel.setRowCount(0);
        for (SaleItem i : items) {
            itemsModel.addRow(new Object[]{i.productName(), i.quantity(),
                    Money.format(i.unitPrice()), Money.format(i.subtotal())});
        }
    }

    public void clearItems() {
        itemsModel.setRowCount(0);
    }

    public void showTodaysTotal(BigDecimal total) {
        todayLabel.setText("Today's sales: " + Money.format(total));
    }

    public void showError(String message) {
        Ui.error(this, message);
    }

