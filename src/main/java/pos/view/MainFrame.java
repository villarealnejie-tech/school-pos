    /** Adds a tab; onSelected runs every time the user switches to it. */
    public void addTab(String title, JPanel panel, Runnable onSelected) {
        onTabSelected.add(onSelected);
        adding = true; // ignore the change event fired while the tab is being added
        tabs.addTab(title, panel);
        adding = false;
    }

